-- Query 1: INNER JOIN - each order with its customer.
SELECT o.order_id, u.full_name, o.order_date, o.status
FROM orders o
INNER JOIN users u ON u.user_id = o.user_id
ORDER BY o.order_id;

-- Query 2: LEFT JOIN - include customers who have never placed an order.
SELECT u.user_id, u.full_name, o.order_id
FROM users u
LEFT JOIN orders o ON o.user_id = u.user_id
ORDER BY u.user_id, o.order_id;

-- Query 3: Multiple joins - order lines with product information.
SELECT o.order_id, p.product_name, oi.quantity, oi.unit_price,
       oi.quantity * oi.unit_price AS line_total
FROM orders o
JOIN order_items oi ON oi.order_id = o.order_id
JOIN products p ON p.product_id = oi.product_id
ORDER BY o.order_id, p.product_id;

-- Query 4: GROUP BY - total value of each order.
SELECT o.order_id, u.full_name,
       SUM(oi.quantity * oi.unit_price) AS order_total
FROM orders o
JOIN users u ON u.user_id = o.user_id
JOIN order_items oi ON oi.order_id = o.order_id
GROUP BY o.order_id, u.full_name
ORDER BY o.order_id;

-- Query 5: GROUP BY + HAVING - customers with at least 4000 spend.
SELECT u.user_id, u.full_name,
       SUM(oi.quantity * oi.unit_price) AS total_spend
FROM users u
JOIN orders o ON o.user_id = u.user_id
JOIN order_items oi ON oi.order_id = o.order_id
WHERE o.status <> 'cancelled'
GROUP BY u.user_id, u.full_name
HAVING SUM(oi.quantity * oi.unit_price) >= 4000
ORDER BY total_spend DESC;

-- Query 6: LEFT JOIN + NULL - products never ordered.
SELECT p.product_id, p.product_name
FROM products p
LEFT JOIN order_items oi ON oi.product_id = p.product_id
WHERE oi.product_id IS NULL
ORDER BY p.product_id;

-- Query 7: Scalar subquery - products priced above average.
SELECT product_id, product_name, unit_price
FROM products
WHERE unit_price > (SELECT AVG(unit_price) FROM products)
ORDER BY unit_price DESC;

-- Query 8: Correlated subquery - each customer's latest order.
SELECT u.user_id, u.full_name, o.order_id, o.order_date
FROM users u
JOIN orders o ON o.user_id = u.user_id
WHERE o.order_date = (
    SELECT MAX(o2.order_date)
    FROM orders o2
    WHERE o2.user_id = u.user_id
)
ORDER BY u.user_id;

-- Query 9: FULL OUTER JOIN - audit unmatched product/order-item rows.
SELECT p.product_id, p.product_name, oi.order_id
FROM products p
FULL OUTER JOIN order_items oi ON oi.product_id = p.product_id
ORDER BY p.product_id NULLS LAST, oi.order_id;

-- Query 10: LEFT JOIN + aggregation - units sold and revenue per product,
-- including products with no sales.
SELECT p.product_id, p.product_name,
       COALESCE(SUM(oi.quantity), 0) AS units_sold,
       COALESCE(SUM(oi.quantity * oi.unit_price), 0.00) AS revenue
FROM products p
LEFT JOIN order_items oi ON oi.product_id = p.product_id
GROUP BY p.product_id, p.product_name
ORDER BY p.product_id;
